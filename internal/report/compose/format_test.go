package compose

import (
	"testing"

	"github.com/shopspring/decimal"
)

func TestFormatNumber(t *testing.T) {
	cases := []struct{ in, format, want string }{
		{"1234567.5", "#,##0.00", "1 234 567,50"},
		{"1234567", "#,##0", "1 234 567"},
		{"0.1234", "0.0%", "12,3%"},
		{"42", "", "42"},
		{"-333.34", "#,##0.00", "-333,34"},

		// Опциональные "#" после точки (issue #460): min 2 — max 6.
		{"409", "#,##0.00####", "409,00"},        // добивается до min 2
		{"430.5", "#,##0.00####", "430,50"},      // один хвостовой ноль остаётся до min
		{"0.345", "#,##0.00####", "0,345"},       // влезает в max, лишнего не добавляем
		{"0.000111", "#,##0.00####", "0,000111"}, // раньше был ложный "0,00"
		{"1.5", "#,##0.00####", "1,50"},
		{"2.1234567", "#,##0.00####", "2,123457"}, // округление до max 6
		// Все "#" после точки — min 0: целое печатается без запятой.
		{"409", "0.##", "409"},
		{"409.5", "0.##", "409,5"},
		{"409.567", "0.##", "409,57"},
		// Процент с опциональными знаками.
		{"0.1", "0.0##%", "10,0%"}, // один обязательный "0" → min 1 знак
		{"0.12345", "0.0##%", "12,345%"},
	}
	for _, c := range cases {
		d, _ := decimal.NewFromString(c.in)
		if got := FormatNumber(d, c.format); got != c.want {
			t.Errorf("FormatNumber(%s,%q)=%q want %q", c.in, c.format, got, c.want)
		}
	}
}
